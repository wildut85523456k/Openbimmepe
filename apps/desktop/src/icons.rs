//! Ribbon and toolbar icons, embedded in the executable.
//!
//! The artwork is the approved 3D icon package (`assets/icons/approved-3d/`), converted to transparent PNGs in
//! `assets/icons/rust/` by `assets/icons/make_rust_icons.py`; Import/Export IFC are redrawn by
//! `assets/icons/make_ifc_icons.py` (the catalog's own IFC icons resemble a trademarked logo). Seven line drawings
//! also have a light-stroke `.dark.png` for the dark theme. Regenerate this table when icons are added.

pub struct Icon { pub id: &'static str, pub light: &'static [u8], pub dark: Option<&'static [u8]> }

macro_rules! icon {
    ($id:literal) => { Icon { id: $id, light: include_bytes!(concat!("../../../assets/icons/rust/", $id, ".png")), dark: None } };
    ($id:literal, dark) => { Icon {
        id: $id,
        light: include_bytes!(concat!("../../../assets/icons/rust/", $id, ".png")),
        dark: Some(include_bytes!(concat!("../../../assets/icons/rust/", $id, ".dark.png"))),
    } };
}

