//! Ribbon and toolbar icons, embedded in the executable.
//! Discipline icons are PNGs cut from the reference sheet `assets/icons/ribbon/source-sheet.png`;
//! common commands are 3D SVGs in `assets/icons/common/`. Some line-drawing icons have a dark-theme variant.
//! Regenerate this table when icons are added (one line per file).

pub struct Icon { pub id: &'static str, pub light: &'static [u8], pub dark: Option<&'static [u8]>, pub svg: bool }

macro_rules! png { ($cat:literal, $id:literal) => { Icon { id: $id, light: include_bytes!(concat!("../../../assets/icons/ribbon/", $cat, "/", $id, ".png")), dark: None, svg: false } } }
macro_rules! png_dark { ($cat:literal, $id:literal) => { Icon { id: $id, light: include_bytes!(concat!("../../../assets/icons/ribbon/", $cat, "/", $id, ".png")), dark: Some(include_bytes!(concat!("../../../assets/icons/ribbon/", $cat, "/", $id, ".dark.png"))), svg: false } } }
macro_rules! svg { ($id:literal) => { Icon { id: $id, light: include_bytes!(concat!("../../../assets/icons/common/", $id, ".svg")), dark: None, svg: true } } }

