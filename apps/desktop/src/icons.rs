/// Command IDs the Rust ribbon uses for which the approved package has a differently named icon.
const ALIASES: &[(&str, &str)] = &[
    ("compute", "systems_analysis"),
    ("save_as", "save"),
    ("elec_compute", "systems_analysis"),
    ("elec_node", "panel"),
    ("elec_cable", "cable_tray"),
    ("end_point", "air_terminal"),
    ("pipe_support", "support"),
    ("valve_gate", "valve"),
    ("revision_cloud", "revision"),
    ("anchor_cast_in", "anchor"), // the package has no separate cast-in anchor drawing yet
];

pub fn find(id: &str) -> Option<&'static Icon> {
    let id = ALIASES.iter().find(|(from, _)| *from == id).map_or(id, |(_, to)| *to);
    ICONS.iter().find(|i| i.id == id)
}
