#!/usr/bin/env bash
# A2: gate subcommand on a FRESH throwaway REPO_ROOT (no leftover state).
EV="$LOCALAPPDATA/Temp/pr72-evidence"
TH="$EV/throwaway-gate"
WT="C:/Users/wilfr/hermes-first-task/revit-alike-wt-pr72"
rm -rf "$TH"; mkdir -p "$TH"
cd "$WT" || exit 9
export REPO_ROOT="$TH"
echo "=== gate no args ==="
bash gh-ctl gate; echo "GATE_NOARG_EXIT=$?"
echo "=== gate target-x 'echo gated-ran' (fresh) ==="
bash gh-ctl gate target-x 'echo gated-ran'; echo "GATE_EXIT=$?"
echo "=== target-x lock released? ==="
ls -A "$TH"
echo "=== gate target-x again (should acquire) ==="
bash gh-ctl gate target-x 'echo gated-again'; echo "GATE2_EXIT=$?"
echo "=== gate contention: pre-create target-y lock, then run ==="
mkdir -p "$TH/target-y"
bash gh-ctl gate target-y 'echo never'; echo "GATE_HELD_EXIT=$?"
rm -rf "$TH/target-y" "$TH/target-y.pid"
echo "=== cargo fresh ==="
CARGO_TIMEOUT=5 bash gh-ctl cargo 'echo cargorun'; echo "CARGO_EXIT=$?"
echo "=== cargo with a queued job ==="
printf '0\techo queued-cargo-ran\n' > "$TH/.gh-ctl/cargo.queue"
CARGO_TIMEOUT=5 bash gh-ctl cargo 'echo cargorun2'; echo "CARGO_Q_EXIT=$?"
echo "=== .gh-ctl final ==="
ls -A "$TH/.gh-ctl"
